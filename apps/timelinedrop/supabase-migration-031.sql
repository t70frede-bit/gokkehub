-- Migration 031 — global song library for quick play
--
-- Quick start previously drew from tl_playlist_catalog, which had exactly one
-- active entry (50 classic-rock tracks, migration 029). Every quick-start room
-- therefore played the same 50 songs, and the per-track Spotify resolution in
-- catalog-import capped a room at 40 of them.
--
-- This table is a large, decade-balanced pool with the release year already
-- resolved, so sampling a room's track list costs ZERO external calls — no
-- Spotify search, no subrequest budget, no cap.
--
-- ── How the rows were built ────────────────────────────────────────────────
-- Song SELECTION came from Deezer's public decade playlists (real, popular,
-- chart-validated tracks). The release YEAR came from the iTunes Search API,
-- which measured 5/6 exact on known remaster-drift traps where Deezer scored
-- 2/6 and MusicBrainz 1/4 (Deezer dated "Imagine" to 2010 and "Hotel
-- California" to 2019 — both compilation reissues).
--
-- Every row then had to pass a cross-check: the iTunes year must fall inside
-- the decade the song was harvested from. A track pulled from an "80s Hits"
-- playlist that iTunes dates to 2011 is a remaster or compilation entry and
-- was dropped. Two independent sources agreeing is the bar, because a wrong
-- year is the worst possible defect in a year-placement game.
--
-- Years here are still not infallible. The existing correction flow
-- (tl_song_corrections, "❓ Correct an issue?" → correct year) applies to
-- these rows exactly as it does to Spotify-sourced ones, and a correction
-- made in any room applies everywhere afterwards.

CREATE TABLE IF NOT EXISTS tl_song_library (
  id           SERIAL PRIMARY KEY,
  artist       TEXT NOT NULL,
  title        TEXT NOT NULL,
  release_year INT  NOT NULL CHECK (release_year BETWEEN 1900 AND 2100),
  -- Denormalised bucket ('1960s' … '2020s'). Kept as a column rather than
  -- derived so the sampling RPC can partition on it directly.
  decade       TEXT NOT NULL,
  source       TEXT NOT NULL DEFAULT 'deezer+itunes',
  is_active    BOOLEAN NOT NULL DEFAULT true,
  added_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- One row per song. Normalised so "Don't Stop Me Now" and "Dont Stop Me
  -- Now" can't both land here from different playlists.
  UNIQUE (artist, title)
);

CREATE INDEX IF NOT EXISTS tl_song_library_decade
  ON tl_song_library (decade) WHERE is_active;

ALTER TABLE tl_song_library ENABLE ROW LEVEL SECURITY;
-- Open read, mirroring tl_playlist_catalog: public song metadata, no room or
-- player association. Writes are service-role only, from Pages Functions.
DROP POLICY IF EXISTS "read_all" ON tl_song_library;
CREATE POLICY "read_all" ON tl_song_library FOR SELECT USING (true);

-- Decade-balanced random sample.
--
-- A naive ORDER BY random() LIMIT n would over-represent whichever decade has
-- the most rows, which flattens the timeline and makes placement a coin flip
-- between adjacent years. Partitioning first guarantees spread across the
-- whole timeline, which is what makes the core mechanic interesting.
CREATE OR REPLACE FUNCTION tl_sample_song_library(n INT DEFAULT 40)
RETURNS TABLE (
  id           INT,
  artist       TEXT,
  title        TEXT,
  release_year INT,
  decade       TEXT
) AS $$
  WITH d AS (
    SELECT count(DISTINCT s.decade) AS n_dec FROM tl_song_library s WHERE s.is_active
  ),
  ranked AS (
    SELECT s.*,
           row_number() OVER (PARTITION BY s.decade ORDER BY random()) AS rn
    FROM tl_song_library s
    WHERE s.is_active
  )
  SELECT r.id, r.artist, r.title, r.release_year, r.decade
  FROM ranked r, d
  -- +1 so a remainder never starves the last decade; the outer LIMIT trims.
  WHERE r.rn <= (n / GREATEST(d.n_dec, 1)) + 1
  ORDER BY random()
  LIMIT GREATEST(n, 1);
$$ LANGUAGE sql VOLATILE;

